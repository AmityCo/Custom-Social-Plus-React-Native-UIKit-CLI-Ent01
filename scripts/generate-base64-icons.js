#!/usr/bin/env node
/**
 * Regenerates the inlined base64 asset modules:
 *   src/core/assets/configs/base64Icons.ts
 *   src/core/assets/images/base64Images.ts
 *
 * Why these are inlined rather than require()'d:
 *
 * React Native's AssetSourceResolver only serves require()'d images over HTTP
 * while Metro is running. In a bundled app it instead returns an Android
 * drawable resource *name*, which ReactDrawableHelper resolves at runtime via
 * Resources.getIdentifier() against the host package. That lookup fails
 * silently wherever the drawables did not survive AAR -> app resource merging,
 * or were dropped by the resource shrinker (nothing references them
 * statically, so they look unused). Brownfield hosts that ship a pre-built
 * bundle hit this, and the images render as blank space.
 *
 * Base64 data URIs travel inside the JS bundle, so they resolve identically in
 * a standalone RN app and in a native host. Total payload is ~48KB.
 *
 * Run after adding or changing any bundled icon/image:
 *   node scripts/generate-base64-icons.js
 */
const fs = require('fs');
const path = require('path');

const ROOT = path.join(__dirname, '..');
const CONFIG_DIR = path.join(ROOT, 'src/core/assets/configs');
const HOOK = path.join(ROOT, 'src/social/hooks/useConfigImageUri.ts');

const HEADER = (what) =>
  `// AUTO-GENERATED by scripts/generate-base64-icons.js - do not edit by hand.\n` +
  `//\n// ${what} inlined as base64 data URIs so they resolve without Metro and\n` +
  `// without depending on Android drawable resources surviving the host app's\n` +
  `// resource merging. See the script header for the full rationale.\n\n`;

function toDataUri(file) {
  return 'data:image/png;base64,' + fs.readFileSync(file).toString('base64');
}

function emit(target, exportName, entries, what) {
  let out =
    HEADER(what) + `export const ${exportName}: Record<string, string> = {\n`;
  for (const [key, file] of entries) {
    out += `  '${key}': '${toDataUri(file)}',\n`;
  }
  out += '};\n';
  fs.writeFileSync(target, out);
  const kb = Math.round(fs.statSync(target).size / 1024);
  console.log(
    `wrote ${path.relative(ROOT, target)} (${entries.length} assets, ${kb}KB)`
  );
}

// Config icons: every PNG referenced by the useConfigImageUri mapping table.
const referenced = new Set(
  [
    ...fs
      .readFileSync(HOOK, 'utf8')
      .matchAll(/light: '([^']+)'|dark: '([^']+)'/g),
  ].map((m) => m[1] || m[2])
);
const iconEntries = [...referenced]
  .sort()
  .map((name) => [name, path.join(CONFIG_DIR, name + '.png')]);

const missing = iconEntries.filter(([, f]) => !fs.existsSync(f));
if (missing.length) {
  console.error('Missing PNGs for:', missing.map(([n]) => n).join(', '));
  process.exit(1);
}

emit(
  path.join(CONFIG_DIR, 'base64Icons.ts'),
  'base64Icons',
  iconEntries,
  'Config-driven icons,'
);

// Standalone bundled images.
emit(
  path.join(ROOT, 'src/core/assets/images/base64Images.ts'),
  'base64Images',
  [
    ['userAvatar', path.join(ROOT, 'src/core/assets/images/userAvatar.png')],
    [
      'communityAvatar',
      path.join(ROOT, 'src/core/assets/images/communityAvatar.png'),
    ],
    ['adAvatar', path.join(ROOT, 'src/core/assets/images/adAvatar.png')],
    [
      'noSearchResult',
      path.join(ROOT, 'src/core/assets/images/noSearchResult.png'),
    ],
    [
      'previewLinkDefaultBackground',
      path.join(
        ROOT,
        'src/core/assets/images/previewLinkDefaultBackground.png'
      ),
    ],
    ['placeholder', path.join(ROOT, 'assets/icon/Placeholder.png')],
  ],
  'Bundled images,'
);
